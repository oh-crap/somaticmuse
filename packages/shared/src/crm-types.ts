// ============================================================
// Composite types for UI (joins used in pages)
// ============================================================

/** Course with its enrolled students (CRM homepage) */
export interface CourseWithStudents {
  id: string;
  title: string;
  yoga_style: string;
  format: string;
  start_at: string;
  end_at: string;
  studio_name: string;
  studio_address: string;
  students: Pick<Student, "id" | "first_name" | "last_name" | "photo_url">[];
}

/** Student with resolved tags (detail page, lists) */
export interface StudentWithTags {
  student: Student;
  tags: (Tag & { last_seen_at: string })[];
}