// ============================================================
// Student
// ============================================================

export interface Student {
  id: string;
  first_name: string;
  last_name: string;
  photo_url: string | null;
  email: string | null;
  phone: string | null;
  facebook_url: string | null;
  instagram_url: string | null;
  notes_health: string | null;
  notes_family: string | null;
  notes_hobbies: string | null;
  notes_other: string | null;
  holiday_until: string | null; // ISO date string (YYYY-MM-DD)
  active: boolean;
  created_at: string;
  updated_at: string;
}

/** For INSERT — id and timestamps generated by DB */
export interface StudentInsert {
  first_name: string;
  last_name: string;
  photo_url?: string | null;
  email?: string | null;
  phone?: string | null;
  facebook_url?: string | null;
  instagram_url?: string | null;
  notes_health?: string | null;
  notes_family?: string | null;
  notes_hobbies?: string | null;
  notes_other?: string | null;
  holiday_until?: string | null;
  active?: boolean;
}

/** For UPDATE — all fields optional */
export type StudentUpdate = Partial<StudentInsert>;

// ============================================================
// Course–Student enrollment (junction)
