export interface CourseStudent {
  id: string;
  course_id: string;
  student_id: string;
  created_at: string;
}

export interface CourseStudentInsert {
  course_id: string;
  student_id: string;
}

// ============================================================
// Tags
// ============================================================

export type TagType = "yoga_style" | "studio" | "format";

export interface Tag {
  id: string;
  type: TagType;
  value: string;
  color: string;
  created_at: string;
}

export interface TagInsert {
  type: TagType;
  value: string;
  color?: string;
}

export type TagUpdate = Partial<Pick<Tag, "value" | "color">>;

// ============================================================
// Student–Tag association
// ============================================================

export interface StudentTag {
  student_id: string;
  tag_id: string;
  last_seen_at: string;
}

export interface StudentTagInsert {
  student_id: string;
  tag_id: string;
  last_seen_at?: string;
}

// ============================================================
// Sleeping students (from DB view)
